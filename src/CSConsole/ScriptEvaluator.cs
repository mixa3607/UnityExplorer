using Mono.CSharp;
using System.Collections.Concurrent;
using UnityExplorer.Config;

// Thanks to ManlyMarco for this

namespace UnityExplorer.CSConsole;

#nullable enable

public sealed class ScriptEvaluator : Evaluator, IDisposable
{
    internal TextWriter TextWriter { private get; set; }
    internal static StreamReportPrinter? _reportPrinter;

    private static readonly HashSet<string> StdLib = new(StringComparer.InvariantCultureIgnoreCase)
    {
        "mscorlib",
        "System.Core",
        "System",
        "System.Xml"
    };

    // AssemblyLoad can fire from any thread, including while Mono.CSharp is enumerating its
    // reference list. Mutating the evaluator from that event produced the
    // "Collection was modified; enumeration operation may not execute" internal compiler errors.
    // Queue the assemblies instead and drain them at a safe point (before the next compile).
    private readonly ConcurrentQueue<Assembly> _pendingReferences = new();
    private readonly HashSet<string> _referencedNames = new(StringComparer.InvariantCultureIgnoreCase);

    public ScriptEvaluator(TextWriter tw)
        : base(BuildContext(tw))
    {
        TextWriter = tw;

        ImportAppdomainAssemblies();
        AppDomain.CurrentDomain.AssemblyLoad += OnAssemblyLoad;
    }

    public override string? ToString()
        => TextWriter.ToString();

    public void Dispose()
    {
        AppDomain.CurrentDomain.AssemblyLoad -= OnAssemblyLoad;
        TextWriter.Dispose();
    }

    public void FlushPendingReferences()
    {
        while (_pendingReferences.TryDequeue(out Assembly? assembly))
        {
            if (assembly != null)
                Reference(assembly);
        }
    }

    private void OnAssemblyLoad(object? _, AssemblyLoadEventArgs args)
    {
        _pendingReferences.Enqueue(args.LoadedAssembly);
    }

    private void Reference(Assembly asm)
    {
        string? name = asm.GetName().Name;

        if (string.IsNullOrEmpty(name) ||
            name == "completions") // ignore assemblies generated by mcs' autocomplete.
        {
            return;
        }

        if (StdLib.Contains(name) || IsBlacklisted(name))
            return;

        if (!_referencedNames.Add(name))
            return;

        try
        {
            ReferenceAssembly(asm);
        }
        catch
        {
            // Not every assembly is usable as a compiler reference; skip it and keep going.
            _referencedNames.Remove(name);
        }
    }

    private static bool IsBlacklisted(string name)
    {
        string blacklist = ConfigManager.CSConsole_Assembly_Blacklist.Value;
        if (string.IsNullOrEmpty(blacklist))
            return false;

        foreach (string blacklisted in blacklist.Split(';'))
        {
            string bl = blacklisted.Trim();
            if (bl.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                bl = bl.Substring(0, bl.Length - 4);

            if (string.Equals(bl, name, StringComparison.OrdinalIgnoreCase))
                return true;
        }

        return false;
    }

    private static CompilerContext BuildContext(TextWriter tw)
    {
        _reportPrinter = new StreamReportPrinter(tw);

        CompilerSettings settings = new()
        {
            Version = LanguageVersion.Experimental,
            GenerateDebugInfo = false,
            StdLib = true,
            Target = Target.Library,
            WarningLevel = 0,
            EnhancedWarnings = false,
            Unsafe = true,
        };

        return new CompilerContext(settings, _reportPrinter);
    }

    private void ImportAppdomainAssemblies()
    {
        foreach (Assembly assembly in AppDomain.CurrentDomain.GetAssemblies())
        {
            string? name = assembly.GetName().Name;
            if (string.IsNullOrEmpty(name) ||
                StdLib.Contains(name))
            {
                continue;
            }

            try
            {
                Reference(assembly);
            }
            catch // (Exception ex)
            {
                //ExplorerCore.LogWarning($"Excepting referencing '{name}': {ex.GetType()}.{ex.Message}");
            }
        }
    }
}
